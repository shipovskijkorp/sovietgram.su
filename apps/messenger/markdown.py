"""CommonMark/GFM rendering for untrusted chat messages.

Only sanitized HTML generated by this module is ever inserted into the chat.
External images require an explicit click and no server-side URL fetch occurs.
The original Markdown is retained for edits, drafts, forwarding and export.
"""
import re
from html import escape
from urllib.parse import urlsplit

import nh3
from django.urls import reverse
from markdown_it import MarkdownIt
from markdown_it.token import Token
from mdit_py_plugins.deflist import deflist_plugin
from mdit_py_plugins.footnote import footnote_plugin
from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import get_lexer_by_name
from pygments.util import ClassNotFound


_SOCIAL = re.compile(
    r"(?<![\w@.+/-])@[\w](?:[\w.+-]*[\w+-])?"
    r"|(?<![\w#/@])#[\w]+",
    re.UNICODE,
)
_SAFE_SCOPE = re.compile(r"^[A-Za-z0-9-]{1,64}$")
_FORMATTER = HtmlFormatter(nowrap=True, classprefix="md-hl-")


def _safe_url(url):
    if not url or "\\" in url or any(ord(char) <= 32 or ord(char) == 127 for char in url):
        return False
    try:
        parts = urlsplit(url)
        if parts.scheme.lower() in {"http", "https"}:
            return bool(parts.hostname)
        if parts.scheme.lower() == "mailto":
            return bool(parts.path)
        # Relative URLs and fragment links are valid Markdown destinations.
        return not parts.scheme and not url.startswith("//") and not parts.netloc
    except ValueError:
        return False


def _external_image_url(url):
    try:
        parts = urlsplit(url)
        return _safe_url(url) and parts.scheme.lower() in {"http", "https"} and bool(parts.hostname)
    except ValueError:
        return False


class ChatMarkdown(MarkdownIt):
    def validateLink(self, url):
        return _safe_url(url)


def _highlight(code, language, attrs):
    if not language or len(language) > 48 or not re.fullmatch(r"[\w.+#-]+", language):
        return ""
    try:
        lexer = get_lexer_by_name(language, stripnl=False, ensurenl=False)
    except ClassNotFound:
        return ""
    return highlight(code, lexer, _FORMATTER)


def _extension(state, silent):
    pos = state.pos
    marker = state.src[pos:pos + 2]
    if marker not in {"||", "++"}:
        return False
    start = pos + 2
    # Keep custom spans single-line and outside fenced/inline code or links.
    end = state.src.find(marker, start, state.posMax)
    if end <= start or "\n" in state.src[start:end]:
        return False
    # Do not interpret an escaped closing delimiter.
    back = end - 1
    while back >= start and state.src[back] == "\\":
        back -= 1
    if (end - 1 - back) % 2:
        return False
    if not silent:
        token = state.push("sg_spoiler" if marker == "||" else "sg_underline", "", 0)
        token.content = state.src[start:end]
    state.pos = end + 2
    return True


def _social_tokens(state):
    # Run after normal Markdown/linkify rules so links and code stay intact.
    for parent in state.tokens:
        if parent.type != "inline" or not parent.children:
            continue
        output = []
        link_depth = 0
        for token in parent.children:
            if token.type == "link_open":
                link_depth += 1
            if token.type == "link_close":
                link_depth = max(0, link_depth - 1)
            if token.type != "text" or link_depth:
                output.append(token)
                continue
            cursor = 0
            for match in _SOCIAL.finditer(token.content):
                word = match.group()
                limit = 151 if word.startswith("@") else 120
                if len(word) > limit:
                    continue
                if match.start() > cursor:
                    text = Token("text", "", 0)
                    text.content = token.content[cursor:match.start()]
                    output.append(text)
                social = Token("sg_mention" if word.startswith("@") else "sg_hashtag", "", 0)
                social.content = word
                output.append(social)
                cursor = match.end()
            if cursor < len(token.content):
                text = Token("text", "", 0)
                text.content = token.content[cursor:]
                output.append(text)
        parent.children = output


def _mention(renderer, tokens, idx, options, env):
    word = tokens[idx].content
    try:
        url = reverse("accounts:public_profile", args=[word[1:]])
    except Exception:
        return escape(word)
    return f'<a href="{escape(url, quote=True)}" data-user-profile="">{escape(word)}</a>'


def _hashtag(renderer, tokens, idx, options, env):
    word = escape(tokens[idx].content, quote=True)
    return f'<button type="button" class="message-hashtag" data-message-hashtag="{word}">{word}</button>'


def _spoiler(renderer, tokens, idx, options, env):
    return (
        '<button type="button" class="message-spoiler" aria-expanded="false" '
        'aria-label="Показать скрытый текст">'
        + escape(tokens[idx].content)
        + "</button>"
    )


def _underline(renderer, tokens, idx, options, env):
    return "<u>" + escape(tokens[idx].content) + "</u>"


def _image(renderer, tokens, idx, options, env):
    token = tokens[idx]
    url = token.attrGet("src") or ""
    alt = renderer.renderInlineAsText(token.children or [], options, env) or "Изображение"
    if not _external_image_url(url):
        return escape(alt)
    return (
        '<button type="button" class="markdown-image-load" data-markdown-image-url="'
        + escape(url, quote=True)
        + '" data-markdown-image-alt="'
        + escape(alt, quote=True)
        + '">Загрузить изображение: '
        + escape(alt)
        + "</button>"
    )


def _link(renderer, tokens, idx, options, env):
    token = tokens[idx]
    href = token.attrGet("href") or ""
    if href.startswith(("http://", "https://", "mailto:")):
        token.attrSet("target", "_blank")
    return renderer.renderToken(tokens, idx, options, env)


def _cell(renderer, tokens, idx, options, env):
    token = tokens[idx]
    style = token.attrGet("style") or ""
    alignment = re.fullmatch(r"text-align:\s*(left|center|right);?", style)
    if alignment:
        token.attrSet("class", "markdown-align-" + alignment.group(1))
    return renderer.renderToken(tokens, idx, options, env)


def _make_parser():
    parser = ChatMarkdown("gfm-like2", {
        "html": False, "breaks": True, "typographer": False,
        "maxNesting": 20, "highlight": _highlight,
    }).use(footnote_plugin).use(deflist_plugin)
    parser.inline.add_terminator_char("+")
    parser.inline.add_terminator_char("|")
    parser.inline.ruler.before("emphasis", "sg_extensions", _extension)
    parser.core.ruler.push("sg_social", _social_tokens)
    for name, rule in {
        "sg_mention": _mention, "sg_hashtag": _hashtag,
        "sg_spoiler": _spoiler, "sg_underline": _underline,
        "image": _image, "link_open": _link, "th_open": _cell, "td_open": _cell,
    }.items():
        parser.add_render_rule(name, rule)
    return parser


_PARSER = _make_parser()

# A second independent allowlist protects against unexpected plugin output.
_TAGS = {
    "p", "br", "hr", "h1", "h2", "h3", "h4", "h5", "h6", "strong", "em", "u",
    "s", "del", "blockquote", "pre", "code", "span", "div", "a", "button",
    "ul", "ol", "li", "table", "thead", "tbody", "tr", "th", "td",
    "input", "section", "sup", "sub", "dl", "dt", "dd",
}
_ATTRS = {
    "*": {"class"},
    "a": {"href", "title", "target", "id", "data-user-profile"},
    "button": {"type", "aria-expanded", "aria-label", "data-message-hashtag",
               "data-markdown-image-url", "data-markdown-image-alt"},
    "input": {"type", "checked", "disabled"},
    "ol": {"start"},
    "li": {"id"},
}


def mentioned_usernames(text):
    """Match actual mention tokens, not email addresses, links or code."""
    if not text or "@" not in text:
        return set()
    tokens = _PARSER.parse(text[:4096], {"docId": "notification"})
    return {
        token.content[1:].casefold()
        for parent in tokens
        for token in parent.children or []
        if token.type == "sg_mention"
    }


def render_message_markdown(text, scope="message"):
    if not text:
        return ""
    scope = scope if _SAFE_SCOPE.fullmatch(scope) else "message"
    # Messages and previews are both bounded by the existing 4096-character limit.
    html = _PARSER.render(text[:4096], {"docId": scope})
    return nh3.clean(
        html, tags=_TAGS, attributes=_ATTRS,
        url_schemes={"http", "https", "mailto"},
        link_rel="noopener noreferrer",
        clean_content_tags={"script", "style"},
    )
